subroutine poly_teos10_bsq(sa,ct,p,r)

use parameters, only: wp
implicit none
real(wp), intent(in) :: sa,ct,p
real(wp), intent(out) :: r
real(wp) :: sau,ctu,zu,deltas
real(wp) :: r00, r01,r02,r03,r04,r05
real(wp) :: r000,r100,r200,r300,r400,r500,r600,r010,r110,r210,r310,r410,r510
real(wp) :: r020,r120,r220,r320,r420,r030,r130,r230,r330,r040,r140,r240,r050,r150
real(wp) :: r060, r001,r101,r201,r301,r401,r011,r111,r211,r311,r021,r121
real(wp) :: r221,r031,r131,r041,r002,r102,r202,r012,r112,r022,r003,r103,r013
real(wp) :: ss,tt,pp,r0,rz3,rz2,rz1,rz0

! reduced variables
sau = 40._wp*35.16504_wp/35._wp
ctu = 40._wp
zu  =1.e4_wp
deltas = 32._wp
ss   = sqrt ( (sa+deltas)/sau )
tt   = ct / ctu
pp   = p / zu

! vertical reference profile of density
r00 = 4.6494977072e+01_wp; r01 = -5.2099962525e+00_wp; r02 = 2.2601900708e-01_wp
r03 = 6.4326772569e-02_wp; r04 = 1.5616995503e-02_wp; r05 = -1.7243708991e-03_wp
r0 = ( ( ( ( ( r05*pp + r04 )*pp + r03 )*pp + r02 )*pp + r01 )*pp + r00 )*pp

! density anomaly
r000 = 8.0189615746e+02_wp ; r100 = 8.6672408165e+02_wp ; r200 = -1.7864682637e+03_wp;
r300 = 2.0375295546e+03_wp ; r400 = -1.2849161071e+03_wp; r500 = 4.3227585684e+02_wp ;
r600 = -6.0579916612e+01_wp; r010 = 2.6010145068e+01_wp ; r110 = -6.5281885265e+01_wp;
r210 = 8.1770425108e+01_wp ; r310 = -5.6888046321e+01_wp; r410 = 1.7681814114e+01_wp ;
r510 = -1.9193502195e+00_wp; r020 = -3.7074170417e+01_wp; r120 = 6.1548258127e+01_wp ;
r220 = -6.0362551501e+01_wp; r320 = 2.9130021253e+01_wp ; r420 = -5.4723692739e+00_wp;
r030 = 2.1661789529e+01_wp ; r130 = -3.3449108469e+01_wp; r230 = 1.9717078466e+01_wp ;
r330 = -3.1742946532e+00_wp; r040 = -8.3627885467e+00_wp; r140 = 1.1311538584e+01_wp ;
r240 = -5.3563304045e+00_wp; r050 = 5.4048723791e-01_wp ; r150 = 4.8169980163e-01_wp ;
r060 = -1.9083568888e-01_wp; r001 = 1.9681925209e+01_wp ; r101 = -4.2549998214e+01_wp;
r201 = 5.0774768218e+01_wp ; r301 = -3.0938076334e+01_wp; r401 = 6.6051753097e+00_wp ;
r011 = -1.3336301113e+01_wp; r111 = -4.4870114575e+00_wp; r211 = 5.0042598061e+00_wp ;
r311 = -6.5399043664e-01_wp; r021 = 6.7080479603e+00_wp ; r121 = 3.5063081279e+00_wp ;
r221 = -1.8795372996e+00_wp; r031 = -2.4649669534e+00_wp; r131 = -5.5077101279e-01_wp;
r041 = 5.5927935970e-01_wp ; r002 = 2.0660924175e+00_wp ; r102 = -4.9527603989e+00_wp;
r202 = 2.5019633244e+00_wp ; r012 = 2.0564311499e+00_wp ; r112 = -2.1311365518e-01_wp;
r022 = -1.2419983026e+00_wp; r003 = -2.3342758797e-02_wp; r103 = -1.8507636718e-02_wp;
r013 = 3.7969820455e-01_wp ;


rz3 =       r013*tt + r103*ss + r003
rz2 =      (r022*tt+r112*ss+r012)*tt+(r202*ss+r102)*ss+r002
rz1 = (((r041*tt+r131 *ss+r031)*tt + &
        (r221*ss+r121)*ss+r021)*tt + &
        ((r311*ss+r211)*ss+r111)*ss+r011)*tt + &
        (((r401*ss+r301)*ss+r201)*ss+r101)*ss+r001

rz0 =  (((((R060*tt+R150*ss+R050)*tt + &
            (R240*ss+R140)*ss+R040)*tt + &
            ((R330*ss+R230)*ss+R130)*ss+R030)*tt + &
        (((R420*ss+R320)*ss+R220)*ss+R120)*ss+R020)*tt + &
        ((((R510*ss+R410)*ss+R310)*ss+R210)*ss+R110)*ss+R010)*tt + &
        (((((R600*ss+R500)*ss+R400)*ss+R300)*ss+R200)*ss+R100)*ss+R000

r = ( ( rz3*pp + rz2 )*pp + rz1 )*pp + rz0

! r = r - 1.e3_wp

end subroutine poly_teos10_bsq